// automorphic-satake-parameters widget — bespoke registry entry.
//
// Bespoke Satake parameter explorer for the automorphic-forms-adelic topic. A slider for the Hecke eigenvalue a_p combined with two select dropdowns for the local component drives an SVG that places the unique-up-to-swap Satake parameters (alpha_p, beta_p) on the unit circle. The slider-plus-two-selects-plus-circle-diagram tri-input layout is specific to the Satake correspondence and does not fit parametric-plot.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
