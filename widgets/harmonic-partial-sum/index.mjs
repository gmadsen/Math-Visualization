// harmonic-partial-sum widget — bespoke registry entry.
//
// Bespoke partial-Fourier-sum visualizer for the harmonic-analysis-fourier topic — target waveform <select> (square / triangle / sawtooth / smooth bump) plus an N slider drive an SVG plot of the partial sum S_N f. The discontinuous targets show the ~9% Gibbs overshoot regardless of N; the smooth bump converges exponentially. Slider+select+svg+readout combo doesn't fit a shared slug.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
