// automorphic-three-conditions widget — bespoke registry entry.
//
// Bespoke conditions-on-phi clickable-list illustration for the automorphic-forms-adelic topic. Reader clicks one of the three conditions defining an automorphic form (left-GL_2(Q)-invariance, right-K-finiteness, moderate growth); the readout reports the consequence of dropping that hypothesis. The single-purpose diagrammed-conditions-list shape is a one-off and does not fit clickable-diagram or counterexample-explorer.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
