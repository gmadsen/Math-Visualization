// characteristic-classes-cpn-localisation widget — bespoke registry entry.
//
// Bespoke equivariant-localisation widget for the characteristic-classes topic — a slider over $ updates the hmtBcfixed points of $\mathbb{CP}^n$ and their tangent-weight contributions, demonstrating that the Atiyah-Bott localisation sum equals $. The integer-$ slider tied to a fixed-point list and weight-sum readout doesn't fit parametric-plot or input-form.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
