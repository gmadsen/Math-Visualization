// automorphic-conductor-ladder widget — bespoke registry entry.
//
// Bespoke local-conductor-exponent ladder for the automorphic-forms-adelic topic. Reader clicks a level on a vertical ladder labeled by p^j; the SVG highlights that rung and the readout reports the dimension of the K_0(p^j)-fixed subspace of pi_p. The clickable-rung shape and conductor-stratification semantics are specific to the local newform theorem and do not fit clickable-diagram.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
