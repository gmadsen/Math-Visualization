// automorphic-functoriality-transfers widget — bespoke registry entry.
//
// Bespoke functoriality-transfer picker for the automorphic-forms-adelic topic. Reader clicks a transfer arrow rho from L-group LH to LG in an SVG of the L-group correspondence diagram; the readout reports the induced action on Satake parameters. The clickable-arrow-on-L-group-correspondence diagram is specific to Langlands functoriality and does not fit clickable-diagram or clickable-graph.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
