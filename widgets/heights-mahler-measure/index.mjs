// heights-mahler-measure widget — bespoke registry entry.
//
// Bespoke Mahler-measure calculator for the heights-arithmetic-geometry topic — a single textarea-style input takes integer polynomial coefficients, and a 'compute' button triggers a multi-line readout showing the leading coefficient, the roots, and M(p) = |a_d| * prod(max(1,|alpha_i|)). The free-form coefficient-list input + root-by-root breakdown readout is bespoke and doesn't fit a shared input/readout slug.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
