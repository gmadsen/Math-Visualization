// automorphic-eisenstein-residue widget — bespoke registry entry.
//
// Bespoke Eisenstein-residue scrubber for the automorphic-forms-adelic topic. A slider over the spectral parameter s drives an SVG that shows the constant term of an Eisenstein series along the line Re(s) = sigma, exposing the simple pole at s = 1 that produces the residual spectrum. The single-slider-plus-pole-plot residue-illustration layout is specific to spectral decomposition and does not fit parametric-plot.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
