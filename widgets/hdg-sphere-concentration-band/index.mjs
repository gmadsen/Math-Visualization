// hdg-sphere-concentration-band widget — bespoke registry entry.
//
// Bespoke widget for §1 sphere concentration on the high-dimensional-geometry topic — slider over dimension n drives an SVG plot of the Lévy concentration tail bound 2 exp(-(n-1) t^2 / 2) collapsing toward t=0, with a readout reporting the tail at a fixed t. The single-slider + svg + readout shape is shared by several siblings on this page but the tail-formula plot logic is bespoke.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
