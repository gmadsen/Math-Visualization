// heights-arakelov-decomposition widget — bespoke registry entry.
//
// Bespoke Arakelov local-global decomposition for the heights-arithmetic-geometry topic — two numeric inputs (rational point coordinates) plus a 'decompose' button trigger a per-place breakdown showing each finite-prime contribution -log|x|_p alongside the archimedean log max(|A|,|B|), then verifies the Artin-Whaples product formula. The per-place tabular readout with running sum check is bespoke and doesn't fit any shared widget.
//
// Exports:
//   renderMarkup(params) -> <div class="widget"> ... </div>
//   renderScript(params) -> <script>\n(function(){ ... })();\n</script>

import { escapeHtml } from '../_shared/escape.mjs';

export function renderMarkup(params) {
  const { widgetId, title, hint, bodyMarkup } = params;
  return (
    `<div class="widget"` + (widgetId ? ` id="${widgetId}"` : "") + `>\n` +
    `  <div class="hd"><div class="ttl">${escapeHtml(title)}</div><div class="hint">${escapeHtml(hint)}</div></div>\n` +
    `${bodyMarkup}\n` +
    `</div>`
  );
}

export function renderScript(params) {
  const { sectionComment, bodyScript } = params;
  const commentLine = sectionComment ? `/* ${sectionComment} */\n` : '';
  return (
    `<script>\n` +
    commentLine +
    `(function(){\n` +
    `${bodyScript}\n` +
    `})();\n` +
    `</script>`
  );
}
