#!/usr/bin/env node
// Builder: tours.html → tours-data.js (the machine-readable tour structure the
// tour-guide banner consumes on topic pages).
//
// tours.html is the single source of truth: 11 `<section class="tour" id=…>`
// blocks, each with an ordered list of `<span class="stop-title"><a href=
// "./page.html#anchor">Title</a></span>` stops. This flattens them into
//   window.MV_TOURS = [{ id, title, color, stops:[{page, anchor, title}] }]
// and writes tours-data.js (a plain `<script>`-loadable assignment, file://-safe
// like the concepts/quizzes bundles). js/tour-banner.js loads it on demand when
// a reader arrives on a stop page via a tour.
//
// Follows the rebuild fix:true convention: default (no flag) is AUDIT — it
// re-derives and exits 1 if the on-disk tours-data.js drifts from tours.html
// (the CI gate, rebuild --no-fix). `--fix` writes the regenerated file.
//
// Stop titles keep their `$…$` KaTeX so the banner can typeset them; everything
// else is plain text. Bespoke raw-byte parser by design (tours.html is a meta
// page the content model never sees), mirroring validate-tour-anchors.mjs.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = !process.argv.includes('--fix'); // audit by default; --fix writes

export function parseTours(toursSrc) {
  const secRe = /<section class="tour" id="([^"]+)"(?:\s+data-color="([^"]+)")?[^>]*>([\s\S]*?)<\/section>/g;
  const tours = [];
  let m;
  while ((m = secRe.exec(toursSrc))) {
    const id = m[1];
    const color = m[2] || '';
    const body = m[3];
    const title = ((body.match(/<h2>([\s\S]*?)<\/h2>/) || [])[1] || id)
      .replace(/<[^>]+>/g, '').replace(/^\d+\.\s*/, '').trim();
    // Stop links tolerate an optional ?query before the #fragment (future-proof).
    const stopRe = /<span class="stop-title"><a href="\.\/([a-zA-Z0-9_-]+\.html)(?:\?[^"#]*)?(?:#([a-zA-Z0-9_:.-]+))?"[^>]*>([\s\S]*?)<\/a>/g;
    const stops = [];
    let s;
    while ((s = stopRe.exec(body))) {
      stops.push({
        page: s[1],
        anchor: s[2] || '',
        title: s[3].replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim(),
      });
    }
    if (stops.length) tours.push({ id, title, color, stops });
  }
  return tours;
}

function render(tours) {
  return '// AUTO-GENERATED by scripts/build-tours-data.mjs from tours.html — do not edit.\n'
    + 'window.MV_TOURS = ' + JSON.stringify(tours, null, 2) + ';\n';
}

const toursSrc = readFileSync(join(repoRoot, 'tours.html'), 'utf8');
const tours = parseTours(toursSrc);
const out = render(tours);
const outPath = join(repoRoot, 'tours-data.js');

if (CHECK) {
  let current = '';
  try { current = readFileSync(outPath, 'utf8'); } catch {}
  if (current !== out) {
    console.error('build-tours-data: tours-data.js is stale vs tours.html — run `node scripts/build-tours-data.mjs`');
    process.exit(1);
  }
  console.log(`build-tours-data: ok (${tours.length} tours, ${tours.reduce((n, t) => n + t.stops.length, 0)} stops)`);
} else {
  writeFileSync(outPath, out);
  console.log(`build-tours-data: wrote tours-data.js (${tours.length} tours, ${tours.reduce((n, t) => n + t.stops.length, 0)} stops)`);
}
